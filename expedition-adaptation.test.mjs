const campaignBosses=['sanctum','drowned-belfry','hunger-kiln','mourning-foundry','sunken-tribunal'];
const crossings=['causeway-entry','terraces-entry','mourning-entry','basin-entry'];
let lastHp=0,lastStr=0;
for(const [index,id] of campaignBosses.entries()){
  assert.ok(enter(campaign,id));
  const boss=campaign.battle.enemies[0];
  assert.ok(boss.maxHp>lastHp&&boss.atk>lastStr);
  lastHp=boss.maxHp;lastStr=boss.atk;
  if(regionalBossMoves[boss.id]){
    const phaseTwo=structuredClone(campaign);
    phaseTwo.battle.enemies[0].hp=Math.floor(boss.maxHp/2);
    for(const die of phaseTwo.battle.dice.filter(die=>die.side==='foe'))die.spent=true;
    assert.ok(endRound(phaseTwo));
    const signature=phaseTwo.battle.dice.find(die=>die.id==='boss0');
    assert.equal(signature.face,regionalBossMoves[boss.id].at(-1));
    assert.equal(signature.fixed,true);
    assert.equal(new Set(dieFaces(phaseTwo,signature)).size,6);
    phaseTwo.modifiers.rerollAll=true;
    rerollDice(phaseTwo);
    assert.equal(signature.face,regionalBossMoves[boss.id].at(-1));
    assert.ok(phaseTwo.battle.dice.find(die=>die.id==='boss1').curse||dieFaces(phaseTwo,signature).includes(phaseTwo.battle.dice.find(die=>die.id==='boss1').face));
  }
  const partyDie=campaign.battle.dice.find(die=>die.id==='party0');
  partyDie.face='strike';
  boss.hp=1;boss.guard=false;boss.ward=0;campaign.battle.defense.foe=0;
  assert.ok(resolve(campaign,partyDie.id,boss.key));
  assert.equal(campaign.phase,'reward');
  const saved=restoreRun(structuredClone(campaign));
  assert.ok(claim(saved,'leave'));
  assert.equal(claim(saved,'leave'),false);
  Object.assign(campaign,saved);
  if(index<crossings.length){
    assert.equal(campaign.phase,'event');
    assert.ok(chooseEvent(campaign,'leave'));
    assert.equal(campaign.phase,'map');
    assert.equal(campaign.node,crossings[index]);
    assert.ok(campaign.visited.includes(id));
    assert.equal(settleRun(freshProgress(),campaign),null);
    const first=available(campaign)[0];
    assert.ok(enter(campaign,first));
    assert.ok(campaign.battle.enemies[0].hp>40);
    assert.ok(restoreRun(structuredClone(campaign)));
    // Use the real route edge immediately before the next boss.
    campaign.battle=null;
    campaign.phase='map';
    campaign.node=nodes.find(node=>node.next.includes(campaignBosses[index+1])).id;
  }
}
