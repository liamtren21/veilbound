const campaign=newRun(42,{runId:'campaign-regression'});
campaign.phase='map';campaign.node='wood-witch';
campaign.heroes[0].equipment[0]='bark-shield';
campaign.heroes[0].level=2;
campaign.pack.equipment.push('juniper-beads');
